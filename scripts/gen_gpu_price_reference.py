"""Generate shared/fleet/vllm_ray/gpu_price_reference.py from docs/reference JSON inputs.

Stdlib only. Any invalid or missing input raises ``ValueError`` and the CLI exits
non-zero; the generator never falls back to partial data.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from typing import Any

VENDOR_CODES: dict[str, int] = {"nvidia": 1, "amd": 2, "intel": 3}
_SLUG = re.compile(r"^(nvidia|amd|intel)-[a-z0-9-]+$")
_INT_FIELDS = ("vram_gb", "tdp_watts", "avg_street_usd")
_DEFAULT_INPUT = Path("docs/reference")
_DEFAULT_OUTPUT = Path("shared/fleet/vllm_ray/gpu_price_reference.py")

_HEADER = '''"""generated by scripts/gen_gpu_price_reference.py — do not edit.

Static street-price / VRAM / TDP reference for every discrete GPU released since 2018
(NVIDIA, AMD, Intel). Regenerate with ``make gen-gpu-price-reference``.
"""

from dataclasses import dataclass


@dataclass(slots=True, frozen=True)
class GpuRef:
    """One GPU class: vendor code, VRAM, TDP, average street price and availability."""

    vendor: int
    gpu_class: str
    vram_gb: int
    tdp_watts: int
    avg_street_usd: int
    availability: str


'''


def _load(input_dir: Path, vendor: str) -> dict[str, Any]:
    """Read and parse one vendor file, failing loudly with the file name."""
    path = input_dir / f"gpu-price-reference-{vendor}.json"
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        raise ValueError(f"cannot read {path.name}: {exc}") from exc
    if not isinstance(data, dict) or not isinstance(data.get("gpus"), list):
        raise ValueError(f"{path.name}: expected an object with a 'gpus' list")
    if data.get("vendor") != vendor:
        raise ValueError(f"{path.name}: file vendor {data.get('vendor')!r} != {vendor!r}")
    return data


def _check_row(file_name: str, vendor: str, row: dict[str, Any]) -> str:
    """Validate one row and return its slug."""
    slug = row.get("class")
    if not isinstance(slug, str) or not _SLUG.match(slug) or not slug.startswith(f"{vendor}-"):
        raise ValueError(f"{file_name}: bad class slug {slug!r} for vendor {vendor}")
    if str(row.get("vendor", "")).lower() != vendor:
        raise ValueError(f"{file_name}: {slug}: row vendor {row.get('vendor')!r} != {vendor!r}")
    for field in _INT_FIELDS:
        value = row.get(field)
        if isinstance(value, bool) or not isinstance(value, int) or value <= 0:
            raise ValueError(f"{file_name}: {slug}: {field} must be a positive int, got {value!r}")
    if not isinstance(row.get("availability"), str) or not row["availability"]:
        raise ValueError(f"{file_name}: {slug}: availability must be non-empty")
    sources = row.get("sources")
    if not isinstance(sources, list) or not sources:
        raise ValueError(f"{file_name}: {slug}: sources must be non-empty")
    return slug


def generate(input_dir: Path) -> str:
    """Return the generated module text for the three vendor files in ``input_dir``."""
    entries: dict[str, tuple[int, dict[str, Any]]] = {}
    as_of: str | None = None
    for vendor, code in VENDOR_CODES.items():
        data = _load(input_dir, vendor)
        file_name = f"gpu-price-reference-{vendor}.json"
        if as_of is None:
            as_of = data.get("as_of")
        elif data.get("as_of") != as_of:
            raise ValueError(f"{file_name}: as_of {data.get('as_of')!r} differs from {as_of!r}")
        for row in data["gpus"]:
            slug = _check_row(file_name, vendor, row)
            if slug in entries:
                raise ValueError(f"{file_name}: duplicate slug {slug}")
            entries[slug] = (code, row)
    if not as_of or not re.fullmatch(r"\d{4}-\d{2}-\d{2}", str(as_of)):
        raise ValueError(f"as_of must be YYYY-MM-DD, got {as_of!r}")
    lines = [_HEADER, f'AS_OF = "{as_of}"\n\n', "GPU_PRICE_REFERENCE: dict[str, GpuRef] = {\n"]
    for slug in sorted(entries):
        code, row = entries[slug]
        lines.append(
            f'    "{slug}": GpuRef(\n'
            f"        vendor={code},\n"
            f'        gpu_class="{slug}",\n'
            f"        vram_gb={row['vram_gb']},\n"
            f"        tdp_watts={row['tdp_watts']},\n"
            f"        avg_street_usd={row['avg_street_usd']},\n"
            f"        availability={json.dumps(row['availability'])},\n"
            f"    ),\n"
        )
    lines.append("}\n")
    return "".join(lines)


def main(argv: list[str] | None = None) -> int:
    """CLI entry: write the module (default) or ``--check`` that it is current."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="exit 1 if the module is stale")
    parser.add_argument("--input-dir", type=Path, default=_DEFAULT_INPUT)
    parser.add_argument("--output", type=Path, default=_DEFAULT_OUTPUT)
    args = parser.parse_args(argv)
    try:
        text = generate(args.input_dir)
    except ValueError as exc:
        print(f"error: {exc}", file=sys.stderr)
        raise SystemExit(1) from exc
    if args.check:
        current = args.output.read_text(encoding="utf-8") if args.output.exists() else None
        if current != text:
            print(f"{args.output} is stale; run make gen-gpu-price-reference", file=sys.stderr)
            raise SystemExit(1)
        return 0
    args.output.write_text(text, encoding="utf-8")
    print(f"wrote {text.count('        gpu_class=')} GPUs")
    return 0


if __name__ == "__main__":
    sys.exit(main())
