#!/usr/bin/env python3
"""Generate rust/crates/auth/src/scopes_generated.rs from shared/auth RBAC.

Python stays the authority for role -> scope bundles; Rust mirrors it.
  usage: gen-rbac-scopes.py [--check]   (--check exits 1 on drift)
Run from anywhere; imports ``shared.auth`` from the repo root.
"""

import sys
from pathlib import Path

root = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(root))

from shared.auth.rbac import ROLE_PERMISSIONS, TEAM_ROLE_PERMISSIONS  # noqa: E402

out = root / "rust/crates/auth/src/scopes_generated.rs"


def emit(name: str, perms) -> str:
    """Render one ``pub(crate) const`` scope list, sorted for stable diffs."""
    items = "".join(f'    "{v}",\n' for v in sorted(p.value for p in perms))
    return f"pub(crate) const {name}: &[&str] = &[\n{items}];\n\n"


body = (
    "// @generated by rust/scripts/gen-rbac-scopes.py from shared/auth/rbac.py -- do not edit.\n"
    "// Drift is gated by `gen-rbac-scopes.py --check` in CI.\n\n"
)
for role, perms in ROLE_PERMISSIONS.items():
    body += emit(f"ROLE_{role.name}", perms)
for trole, perms in TEAM_ROLE_PERMISSIONS.items():
    body += emit(f"TEAM_{trole.name}", perms)

body = body.rstrip() + "\n"  # single trailing newline (end-of-file-fixer parity)

if "--check" in sys.argv:
    if not out.exists() or out.read_text() != body:
        print("scopes_generated.rs drifted from shared/auth/rbac.py", file=sys.stderr)
        sys.exit(1)
    counts = f"{len(ROLE_PERMISSIONS)} roles, {len(TEAM_ROLE_PERMISSIONS)} team roles"
    print(f"scopes_generated.rs in sync ({counts})")
else:
    out.write_text(body)
    print(f"wrote {out}")
